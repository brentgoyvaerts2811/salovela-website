/* ===== Tijdscan-overdracht =====
   Komt de bezoeker van de tijdscan, dan staat zijn resultaat als gestructureerde
   data in sessionStorage. We tonen dat hier als visueel overzicht en sturen het
   mee in een verborgen veld. Het berichtveld blijft vrij voor eigen woorden. */

const scanSummaryEl = document.getElementById("scan-summary");

if (scanSummaryEl) {
  const WEEKS_PER_MONTH = 4.33;
  const DAYS_PER_WEEK = 5;

  let scanData = null;

  try {
    const raw = sessionStorage.getItem("salovela-scan");
    if (raw) {
      sessionStorage.removeItem("salovela-scan");
      scanData = JSON.parse(raw);
    }
  } catch (err) {
    /* Geen sessionStorage of onleesbare inhoud: we tonen gewoon niets. */
  }

  const renderScanSummary = () => {
    if (!scanData) return;

    const lang = document.documentElement.lang === "en" ? "en" : "nl";
    const loc = lang === "en" ? "en-GB" : "nl-BE";
    const dict = translations[lang];
    const t = (key) => dict[key] || key;
    const fillIn = (key, vars) =>
      t(key).replace(/\{(\w+)\}/g, (m, name) => (name in vars ? vars[name] : m));

    const factor = scanData.unit === "dag" ? DAYS_PER_WEEK : 1;
    const unitLabel = t(scanData.unit === "dag" ? "scan.hours.perday" : "scan.hours.perweek");
    const dec = scanData.unit === "dag" ? 2 : 1;
    const hrs = (weekHours) =>
      (weekHours / factor).toLocaleString(loc, { maximumFractionDigits: dec }) + " " + unitLabel;
    const euro = (value) => "€ " + Math.round(value).toLocaleString(loc);

    const peak = scanData.tasks.reduce((max, row) => Math.max(max, row.hours), 0) || 1;
    const money = scanData.recHours * WEEKS_PER_MONTH * 12 * scanData.rate;

    const bars = scanData.tasks.map((row) => {
      const total = (row.hours / peak) * 100;
      const supported = (row.hours * row.auto / peak) * 100;
      return `
        <div class="scan-sum-row">
          <span class="scan-sum-name">${t("scan.task." + row.id)}</span>
          <span class="scan-sum-bar">
            <span class="scan-sum-bar-total" style="width:${total.toFixed(1)}%"></span>
            <span class="scan-sum-bar-fill" style="width:${supported.toFixed(1)}%"></span>
          </span>
          <span class="scan-sum-hours">${hrs(row.hours)}</span>
        </div>`;
    }).join("");

    document.getElementById("scan-summary-body").innerHTML = `
      <p class="scan-sum-sector">${t("scan.sector." + scanData.sector)}</p>
      <div class="scan-sum-chart">${bars}</div>
      <p class="scan-sum-legend">${t("scan.summary.legend")}</p>
      <div class="scan-sum-stats">
        <span><small>${t("scan.summary.total")}</small>${hrs(scanData.totalHours)}</span>
        <span><small>${t("scan.summary.estimate")}</small>${hrs(scanData.recHours)}</span>
        <span><small>${fillIn("scan.summary.peryear", { rate: euro(scanData.rate) })}</small>${euro(money)}</span>
      </div>
      <p class="scan-sum-focus"><small>${t("scan.summary.focus")}</small> ${t("scan.task." + scanData.topTask)}</p>`;

    // Platte tekstversie voor in de mail, zodat het overzicht ook daar leesbaar is.
    const lines = scanData.tasks.map(
      (row) => "  - " + t("scan.task." + row.id) + ": " + hrs(row.hours) +
               " (" + Math.round(row.auto * 100) + "% → " + hrs(row.hours * row.auto) + ")"
    );

    const scanField = document.getElementById("form-scan");
    if (scanField) {
      scanField.value = [
        t("scan.sector." + scanData.sector),
        "",
        ...lines,
        "",
        t("scan.summary.total") + ": " + hrs(scanData.totalHours),
        t("scan.summary.estimate") + ": " + hrs(scanData.recHours) + " — " + euro(money) + " " +
          fillIn("scan.summary.peryear", { rate: euro(scanData.rate) }),
        t("scan.summary.focus") + ": " + t("scan.task." + scanData.topTask)
      ].join("\n");
    }

    const subjectEl = document.getElementById("form-subject");
    if (subjectEl) {
      subjectEl.value = fillIn("scan.handover.subject", {
        sector: t("scan.sector." + scanData.sector)
      });
    }
  };

  if (scanData) {
    scanSummaryEl.hidden = false;
    renderScanSummary();
    document.addEventListener("salovela:langchange", renderScanSummary);

    document.getElementById("scan-summary-remove").addEventListener("click", () => {
      scanData = null;
      scanSummaryEl.hidden = true;
      const scanField = document.getElementById("form-scan");
      const subjectEl = document.getElementById("form-subject");
      if (scanField) scanField.value = "";
      if (subjectEl) {
        const lang = document.documentElement.lang === "en" ? "en" : "nl";
        subjectEl.value = translations[lang]["contact.form.subjectDefault"] ||
          "Aanvraag via website: Algemene vraag";
      }
    });
  }
}

const contactForm = document.getElementById("contact-form");

if (contactForm) {
  const formStatus = document.getElementById("form-status");
  const submitButton = document.getElementById("form-submit");

  contactForm.addEventListener("submit", (event) => {
    event.preventDefault();

    const lang = document.documentElement.lang === "en" ? "en" : "nl";
    const originalLabel = translations[lang]["contact.form.submit"];

    submitButton.disabled = true;
    submitButton.textContent = translations[lang]["contact.form.sending"];
    formStatus.textContent = "";
    formStatus.className = "form-status";

    fetch("https://api.web3forms.com/submit", {
      method: "POST",
      headers: { "Content-Type": "application/json", Accept: "application/json" },
      body: JSON.stringify(Object.fromEntries(new FormData(contactForm))),
    })
      .then((response) => response.json())
      .then((result) => {
        if (result.success) {
          formStatus.textContent = translations[lang]["contact.form.success"];
          formStatus.classList.add("success");
          contactForm.reset();
        } else {
          formStatus.textContent = translations[lang]["contact.form.error"];
          formStatus.classList.add("error");
        }
      })
      .catch(() => {
        formStatus.textContent = translations[lang]["contact.form.error"];
        formStatus.classList.add("error");
      })
      .finally(() => {
        submitButton.disabled = false;
        submitButton.textContent = originalLabel;
      });
  });
}
