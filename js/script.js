function applyLanguage(lang) {
  document.documentElement.lang = lang;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    const text = translations[lang][key];
    if (text) el.textContent = text;
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    const text = translations[lang][key];
    if (text) el.setAttribute("placeholder", text);
  });

  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    const key = el.getAttribute("data-i18n-html");
    const html = translations[lang][key];
    if (html) el.innerHTML = html;
  });

  document.querySelectorAll(".lang-option").forEach((el) => {
    el.classList.toggle("active", el.dataset.lang === lang);
  });

  localStorage.setItem("salovela-lang", lang);

  // Pages with JS-generated content (e.g. the scan) listen for this to re-render.
  document.dispatchEvent(new CustomEvent("salovela:langchange", { detail: { lang } }));
}

